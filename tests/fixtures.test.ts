import { describe, expect, it } from "vitest";
import { renderMarkdown } from "../src/render.js";
import { loadFixture, verdictOf } from "./helpers.js";

describe("fixtures", () => {
  it("receipts an honest pull request as checks out", () => {
    const { receipt } = loadFixture("honest.json");
    const markdown = renderMarkdown(receipt);
    expect(receipt.overall).toBe("checks_out");
    expect(receipt.agent).toEqual({ name: "GitHub Copilot", detected_by: "author" });
    expect(receipt.task).toEqual({ source: "issue#3", text: "Add a health check endpoint" });
    expect(verdictOf(receipt, "tests_pass")).toBe("confirmed");
    expect(verdictOf(receipt, "added_tests")).toBe("confirmed");
    expect(verdictOf(receipt, "file_changed")).toBe("confirmed");
    expect(verdictOf(receipt, "fixed_issue")).toBe("confirmed");
    expect(receipt.red_flags).toEqual([]);
    expect(markdown).toContain("Checks out");
    expect(markdown).toContain("issue #3");
    expect(markdown.toLowerCase()).not.toMatch(/\bverified\b/);
  });

  it("contradicts a false tests-passed claim", () => {
    const { receipt } = loadFixture("false-tests-pass.json");
    const markdown = renderMarkdown(receipt);
    expect(receipt.agent.name).toBe("OpenAI Codex");
    expect(verdictOf(receipt, "tests_pass")).toBe("contradicted");
    expect(verdictOf(receipt, "added_tests")).toBe("confirmed");
    expect(receipt.overall).toBe("doesnt_match");
    expect(receipt.red_flags).toEqual([]);
    expect(markdown).toContain("Doesn't match");
    expect(markdown).toContain("failed");
    expect(markdown).toContain("[View run](https://github.com/omsocll/demo/actions/runs/101)");
  });

  it("does not trust a green check when tests were deleted, skipped, and weakened", () => {
    const { receipt } = loadFixture("deleted-tests.json");
    const markdown = renderMarkdown(receipt);
    expect(verdictOf(receipt, "tests_pass")).toBe("contradicted");
    expect(receipt.overall).toBe("doesnt_match");
    expect(receipt.red_flags.map((flag) => flag.kind).sort()).toEqual([
      "assertions_removed",
      "test_command_weakened",
      "tests_deleted",
      "tests_skipped",
    ]);
    expect(markdown).toContain("src/auth.test.ts");
    expect(markdown).toContain(".skip");
    expect(markdown).toContain("|| true");
    expect(markdown).toContain("A green run does not count.");
    expect(markdown).not.toContain("exact version of the code passed");
    expect(markdown).toContain("Doesn't match");
  });

  it("flags a pass claim when CI never ran", () => {
    const { receipt } = loadFixture("ci-never-ran.json");
    expect(receipt.agent.name).toBe("Cursor");
    expect(verdictOf(receipt, "tests_pass")).toBe("unverifiable");
    expect(receipt.red_flags).toEqual([]);
    expect(receipt.overall).toBe("partly_checked");
    expect(receipt.unverified?.some((line) => line.includes("All tests pass"))).toBe(true);
    expect(receipt.unverified?.some((line) => /no ci checks have reported a result/i.test(line))).toBe(true);
  });

  it("renders the partly checked story in plain English", () => {
    const { receipt } = loadFixture("partly-checked.json");
    const markdown = renderMarkdown(receipt);
    expect(receipt.id).toBe("omsocll-demo-pr-42-3f9c2e1");
    expect(receipt.created_at).toBe("2026-10-19T09:40:00Z");
    expect(receipt.overall).toBe("partly_checked");
    expect(receipt.changes).toMatchObject({ files_changed: 4, additions: 120, deletions: 8 });
    expect(verdictOf(receipt, "tests_pass")).toBe("confirmed");
    expect(verdictOf(receipt, "file_changed")).toBe("confirmed");
    expect(verdictOf(receipt, "other")).toBe("unverifiable");
    expect(markdown).toContain("**🧾 Receipt: PR #42 in omsocll/demo · Partly checked**");
    expect(markdown).toContain("Add dark mode toggle to settings page (issue #17).");
    expect(markdown).toContain("120 lines added and 8 removed");
    expect(markdown).toContain("*\"All tests pass\"*: confirmed.");
    expect(markdown).toContain("`src/Settings.tsx` was changed.");
    expect(markdown).toContain("*\"Works on mobile\"*");
    expect(markdown).toContain("**What we couldn't verify:**");
    expect(markdown).toContain("One claim still needs a human to look at it.");
    expect(markdown).toContain("Generated by proofslip v0.1.1");
    expect(markdown).toContain("It is not a code review.");
  });
});
