import { describe, expect, it } from "vitest";
import { detectAgent } from "../src/agents.js";
import { eventCommitSha, eventHeadBranch, resolvePullRequestNumber } from "../src/event.js";
import { findReceiptComment, upsertIndex, type IndexEntry } from "../src/github.js";
import type { PrEvidence } from "../src/types.js";

function pull(overrides: Partial<PrEvidence> = {}): PrEvidence {
  return {
    repo: "acme/widget",
    number: 4,
    url: "https://github.com/acme/widget/pull/4",
    title: "Change",
    body: "",
    author: "ada",
    headSha: "abc",
    additions: 0,
    deletions: 0,
    files: [],
    ...overrides,
  };
}

describe("agent detection", () => {
  it("recognises known bot authors", () => {
    expect(detectAgent(pull({ author: "copilot-swe-agent[bot]" }))).toMatchObject({
      isAgent: true,
      name: "GitHub Copilot",
      detectedBy: "author",
    });
    expect(detectAgent(pull({ author: "Copilot" })).name).toBe("GitHub Copilot");
    expect(detectAgent(pull({ author: "google-labs-jules[bot]" }))).toMatchObject({
      isAgent: true,
      name: "Jules",
      detectedBy: "author",
    });
    expect(detectAgent(pull({ author: "gemini-code-assist[bot]" })).name).toBe("Gemini");
    expect(detectAgent(pull({ author: "amazon-q-developer[bot]" })).name).toBe("Amazon Q");
  });

  it("recognises a label and an extra login", () => {
    expect(detectAgent(pull({ labels: ["Agent"] })).isAgent).toBe(true);
    expect(detectAgent(pull({ author: "my-agent[bot]" }), { extraLogins: ["my-agent[bot]"] })).toMatchObject({
      isAgent: true,
      detectedBy: "author",
    });
  });

  it("recognises commit trailers", () => {
    const copilot = detectAgent(pull({
      commits: [{ sha: "1", message: "Do it\n\nCo-authored-by: Copilot <copilot@github.com>" }],
    }));
    expect(copilot).toMatchObject({ isAgent: true, name: "GitHub Copilot", detectedBy: "commit_trailer" });

    const logs = detectAgent(pull({
      commits: [{ sha: "1", message: "Do it\n\nAgent-Logs-Url: https://github.com/example/logs/1" }],
    }));
    expect(logs.detectedBy).toBe("commit_trailer");
  });

  it("recognises a Generated by Codex footer when the author is human", () => {
    expect(detectAgent(pull({ author: "ada", body: "Describe the kit paths.\n\nGenerated by Codex" }))).toMatchObject({
      isAgent: true,
      name: "OpenAI Codex",
      detectedBy: "body_marker",
    });
    expect(detectAgent(pull({ author: "ada", body: "Translate the guide.\n\nGenerated-by: codex" }))).toMatchObject({
      isAgent: true,
      name: "OpenAI Codex",
      detectedBy: "body_marker",
    });
    expect(detectAgent(pull({ author: "ada", body: "Assisted-by: codex" }))).toMatchObject({
      isAgent: true,
      name: "OpenAI Codex",
      detectedBy: "body_marker",
    });
    expect(detectAgent(pull({
      author: "ada",
      commits: [{ sha: "1", message: "docs: translate\n\nGenerated-by: codex\n" }],
    }))).toMatchObject({
      isAgent: true,
      name: "OpenAI Codex",
      detectedBy: "commit_trailer",
    });
    expect(detectAgent(pull({ author: "chatgpt-codex-connector[bot]" })).name).toBe("OpenAI Codex");
  });

  it("leaves a human pull request unspecified", () => {
    expect(detectAgent(pull())).toMatchObject({ isAgent: false, detectedBy: "unspecified", name: "ada" });
  });
});

describe("pull request events", () => {
  it("reads the number from pull_request and check_suite payloads", () => {
    expect(resolvePullRequestNumber("pull_request", { pull_request: { number: 9 } })).toBe(9);
    expect(resolvePullRequestNumber("check_suite", { check_suite: { pull_requests: [{ number: 4 }] } })).toBe(4);
    expect(resolvePullRequestNumber("check_suite", { check_suite: { pull_requests: [] } })).toBeNull();
    expect(resolvePullRequestNumber("workflow_dispatch", {}, "15")).toBe(15);
    expect(resolvePullRequestNumber("workflow_run", { workflow_run: { pull_requests: [{ number: 8 }] } })).toBe(8);
    expect(resolvePullRequestNumber("workflow_run", { workflow_run: { pull_requests: [], head_sha: "abc" } })).toBeNull();
    expect(eventCommitSha("workflow_run", { workflow_run: { head_sha: "abc", head_branch: "demo" } })).toBe("abc");
    expect(eventHeadBranch("workflow_run", { workflow_run: { head_branch: "demo" } })).toBe("demo");
    expect(eventCommitSha("check_suite", { check_suite: { head_sha: "def", pull_requests: [] } })).toBe("def");
    expect(eventCommitSha("pull_request", { pull_request: { number: 3, head: { sha: "ghi", ref: "feature" } } })).toBe("ghi");
  });
});

describe("receipt publishing helpers", () => {
  it("finds the sticky comment and upserts the index", () => {
    const comments = [
      { id: 1, body: "looks good" },
      { id: 2, body: "<!-- proofslip-receipt -->\nreceipt" },
    ];
    expect(findReceiptComment(comments)?.id).toBe(2);
    const first: IndexEntry = {
      id: "a",
      repo: "acme/widget",
      pr: 1,
      url: "https://example.test/1",
      head_sha: "abc",
      overall: "checks_out",
      created_at: "2026-10-19T09:00:00Z",
      summary_plain: "first",
      agent: "GitHub Copilot",
    };
    const second = { ...first, id: "b", created_at: "2026-10-19T10:00:00Z", summary_plain: "second" };
    const updated = { ...first, summary_plain: "revised" };
    expect(upsertIndex([first], second).map((entry) => entry.id)).toEqual(["b", "a"]);
    expect(upsertIndex([second, first], updated).map((entry) => entry.summary_plain)).toEqual(["second", "revised"]);
  });
});
